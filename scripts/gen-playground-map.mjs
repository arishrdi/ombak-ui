// Generates components/site/playground-map.tsx: slug → component, for the props playground.
// The component is the export whose name matches `export type <Name>Props`.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const registry = JSON.parse(fs.readFileSync(path.join(root, "registry.json"), "utf8"));
const lines = [];
const entries = [];

for (const item of registry.items.filter((i) => i.type === "registry:component")) {
  const src = fs.readFileSync(path.join(root, "registry", "ombak", item.name, `${item.name}.tsx`), "utf8");
  const name = src.match(/export type (\w+)Props\b/)?.[1];
  if (!name || !new RegExp(`export function ${name}\\b`).test(src)) continue;
  lines.push(`import { ${name} } from "@/registry/ombak/${item.name}/${item.name}";`);
  entries.push(`  ${JSON.stringify(item.name)}: { Component: ${name} as AnyComponent, exportName: ${JSON.stringify(name)} },`);
}

const out = `"use client";

// Generated by scripts/gen-playground-map.mjs (runs in \`npm run registry:build\`). Do not edit by hand.
import type { ComponentType } from "react";
${lines.join("\n")}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type AnyComponent = ComponentType<any>;

export const playgroundMap: Record<string, { Component: AnyComponent; exportName: string }> = {
${entries.join("\n")}
};
`;
fs.writeFileSync(path.join(root, "components", "site", "playground-map.tsx"), out);
console.log(`Playground map: ${entries.length} components.`);
